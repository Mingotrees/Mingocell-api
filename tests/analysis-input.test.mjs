import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm,symlink} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
import {prepareClassifierInput} from '../dist/analysis/input.js';
test('classifier input uses immutable original bytes, verifies hash and selects exact TIFF page',{skip:!process.env.CLASSIFIER_PYTHON && 'Set CLASSIFIER_PYTHON to a Pillow 13.0.0 environment'},async t=>{
  const root=await mkdtemp(join(tmpdir(),'analysis-input-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const storage={root};const config={pythonPath:process.env.CLASSIFIER_PYTHON};
  const signal=new AbortController().signal;
  const bytes=await sharp({create:{width:4,height:4,channels:3,background:'#ff0000'}}).png().toBuffer();
  await writeFile(join(root,'original.png'),bytes);
  const claim={originalStorageKey:'original.png',originalSha256:createHash('sha256').update(bytes).digest('hex'),format:'png',pageIndex:0,pageCount:1};
  const input=await prepareClassifierInput(claim,storage,config,signal);
  assert.deepEqual(Buffer.from(input.bytes),bytes);
  assert.equal(input.extractionVersion,'original-bytes-v1');
  await assert.rejects(prepareClassifierInput({...claim,originalSha256:'0'.repeat(64)},storage,config,signal),e=>e.code==='ORIGINAL_INTEGRITY_FAILED');
  await symlink(join(root,'original.png'),join(root,'link.png'));
  await assert.rejects(prepareClassifierInput({...claim,originalStorageKey:'link.png'},storage,config,signal));
  const tiff=await sharp([{create:{width:4,height:4,channels:3,background:'#ff0000'}},{create:{width:4,height:4,channels:3,background:'#0000ff'}}],{join:{animated:true}}).tiff({compression:'lzw'}).toBuffer();
  await writeFile(join(root,'original.tif'),tiff);
  const multi={...claim,originalStorageKey:'original.tif',originalSha256:createHash('sha256').update(tiff).digest('hex'),format:'tiff',pageIndex:1,pageCount:2};
  const extracted=await prepareClassifierInput(multi,storage,config,signal);
  const pixel=await sharp(extracted.bytes).raw().toBuffer();
  assert.deepEqual([...pixel.subarray(0,3)],[0,0,255]);
  assert.equal(extracted.extractionVersion,'pillow-page-rgb-v1');
  await assert.rejects(prepareClassifierInput(multi,storage,{pythonPath:'/does/not/exist'},signal),e=>e.classification==='suspend');
  const controller=new AbortController();controller.abort();
  await assert.rejects(prepareClassifierInput(multi,storage,config,controller.signal));
});
